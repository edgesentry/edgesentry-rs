//! HTML escaping helpers for rendered document reports.

/// Escape text for safe interpolation into HTML element content and double-quoted attributes.
pub fn escape_html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}
